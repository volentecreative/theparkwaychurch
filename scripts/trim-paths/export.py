# Collect the traced pen lines into src/script-draw-paths.js. Usage: python export.py Winter Spring ...
import sys, json, re
data = {}
for w in sys.argv[1:]:
    d = json.load(open(f'scripts/trim-paths/out/{w}-paths.json'))
    for p in d['paths']:
        p['d'] = re.sub(r'(?<![\d.])0\.', '.', p['d']).replace(' -', '-')  # shorter numbers
    data[w] = {'width': d['width'], 'paths': d['paths']}
js = ('/* Generated by scripts/trim-paths/ from the site font. Do not edit by hand.\n'
      '   Each word: the pen line (centerline, in writing order) in em units from the text origin and\n'
      '   baseline; width = how thick the pen must be to cover the letters. */\n'
      'window.__scriptDrawPaths = ' + json.dumps(data, separators=(',', ':')) + ';\n')
open('src/script-draw-paths.js', 'w').write(js)
print('src/script-draw-paths.js', len(js), 'bytes,', ', '.join(data))
